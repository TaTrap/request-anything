package oracle

import (
	"context"

	"github.com/TaTrap/request-anything/pkg/models"
)

// SessionHandle uniquely identifies an open native session inside a sidecar/worker.
type SessionHandle string

// SessionConfig configures opening a native signing/telemetry session.
type SessionConfig struct {
	AppVersion string            `json:"app_version"`
	DeviceID   string            `json:"device_id"`
	InstallID  string            `json:"install_id"`
	PinnedSeed uint32            `json:"pinned_seed,omitempty"`
	NowMs      int64             `json:"now_ms,omitempty"`
	Extra      map[string]string `json:"extra,omitempty"`
}

// NativeSnapshot is a portable, disk-serializable native runtime snapshot surviving JVM/sidecar restarts.
type NativeSnapshot struct {
	SnapshotID    string `json:"snapshot_id,omitempty"` // Optional in-memory cache key inside live sidecar
	SchemaVersion string `json:"schema_version"`
	AppVersion    string `json:"app_version"`
	DeviceID      string `json:"device_id"`
	InstallID     string `json:"install_id"`
	Payload       []byte `json:"payload"` // Portable serialized state
}

// SignInput carries the request metadata required by the native signer.
type SignInput struct {
	Method   string            `json:"method"`
	URL      string            `json:"url"`
	RawQuery string            `json:"raw_query"`
	Headers  []models.HeaderKV `json:"headers"`
	Body     []byte            `json:"body,omitempty"`
	NowMs    int64             `json:"now_ms,omitempty"`
	Seed     uint32            `json:"seed,omitempty"`
}

// SignOutput returns generated signature headers/query updates plus any immediately queued async packets.
type SignOutput struct {
	Headers     map[string]string `json:"headers,omitempty"`
	QueryParams map[string]string `json:"query_params,omitempty"`
	Queued      []AsyncPacket     `json:"queued,omitempty"`
}

// AsyncPacket represents an out-of-band binary packet emitted by the native worker (e.g. /telemetry/report).
type AsyncPacket struct {
	PacketID  string            `json:"packet_id"`
	Endpoint  string            `json:"endpoint"`
	Method    string            `json:"method"`
	Headers   map[string]string `json:"headers,omitempty"`
	Body      []byte            `json:"body,omitempty"`
	Triggered string            `json:"triggered_by_req_id,omitempty"`
}

// OracleHealth reports whether the native worker has encountered unhandled exceptions or crashes.
type OracleHealth struct {
	Healthy          bool     `json:"healthy"`
	WorkerExceptions int      `json:"worker_exceptions"`
	LastError        string   `json:"last_error,omitempty"`
	ActiveHandles    int      `json:"active_handles"`
	Notes            []string `json:"notes,omitempty"`
}

// DeliverResult holds follow-up packets and health generated by delivering a response to the native worker.
type DeliverResult struct {
	Packets   []AsyncPacket `json:"packets,omitempty"`
	Health    *OracleHealth `json:"health,omitempty"`
	Completed bool          `json:"completed"`
}

// NativeOracle defines the stateful contract with an external/in-process native runtime (unidbg/Frida/native SDK).
type NativeOracle interface {
	Open(ctx context.Context, cfg SessionConfig) (SessionHandle, error)
	Snapshot(ctx context.Context, h SessionHandle) (*NativeSnapshot, error)
	Restore(ctx context.Context, h SessionHandle, snap *NativeSnapshot) error
	Close(ctx context.Context, h SessionHandle) error

	Sign(ctx context.Context, h SessionHandle, reqID string, in SignInput) (*SignOutput, error)
	PendingPackets(ctx context.Context, h SessionHandle) ([]AsyncPacket, error)
	DeliverResponse(ctx context.Context, h SessionHandle, reqID string, resp *models.WireResponse) (*DeliverResult, error)
	Health(ctx context.Context, h SessionHandle) (*OracleHealth, error)
}
