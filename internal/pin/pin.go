package pin

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"sync"
)

const (
	FileName = "pinned.json"
	EnvNowMs = "REQUEST_ANYTHING_NOW_MS"
	EnvSeed  = "REQUEST_ANYTHING_SEED"
	EnvCase  = "REQUEST_ANYTHING_CASE"
)

// Pin locks wall-clock time and Mulberry32 PRNG seed for deterministic Go-side fields.
// NOTE: This controls Go code calling pin/pinned_gen only; native .so / libc RNG requires sidecar virtualization.
type Pin struct {
	NowMs int64  `json:"now_ms"`
	Seed  uint32 `json:"seed"`
}

// DefaultPin returns deterministic reference pin values matching rust-anything's pin.rs.
func DefaultPin() Pin {
	return Pin{
		NowMs: 1700000000000,
		Seed:  1,
	}
}

// Save writes pinned.json into unitDir.
func Save(unitDir string, p Pin) error {
	data, err := json.MarshalIndent(p, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(unitDir, FileName), append(data, '\n'), 0o644)
}

// Load reads pinned.json if present.
func Load(unitDir string) (*Pin, error) {
	path := filepath.Join(unitDir, FileName)
	data, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var p Pin
	if err := json.Unmarshal(data, &p); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}
	return &p, nil
}

// Mulberry32 matches the exact bit-level PRNG used by rust-anything (`src/pin.rs`).
type Mulberry32 struct {
	mu       sync.Mutex
	state    uint32
	lastCase string
	started  bool
}

// NewMulberry32 initializes a Mulberry32 generator from seed.
func NewMulberry32(seed uint32) *Mulberry32 {
	return &Mulberry32{state: seed, started: true}
}

// NextU32 advances the state by one step and returns the next 32 bits.
func (m *Mulberry32) NextU32() uint32 {
	m.mu.Lock()
	defer m.mu.Unlock()
	if !m.started {
		m.started = true
	}
	m.state += 0x6D2B79F5
	t := (m.state ^ (m.state >> 15)) * (m.state | 1)
	t ^= t + ((t ^ (t >> 7)) * (t | 61))
	return t ^ (t >> 14)
}

// Random returns a float64 in [0, 1).
func (m *Mulberry32) Random() float64 {
	return float64(m.NextU32()) / 4294967296.0
}

// Sequence returns N deterministic uint32 outputs for a given seed (useful for tests & verification).
func Sequence(seed uint32, n int) []uint32 {
	g := NewMulberry32(seed)
	out := make([]uint32, n)
	for i := 0; i < n; i++ {
		out[i] = g.NextU32()
	}
	return out
}

// NowMsFromEnv returns pinned millisecond timestamp if EnvNowMs is set, else fallback.
func NowMsFromEnv(fallback int64) int64 {
	if raw := os.Getenv(EnvNowMs); raw != "" {
		if v, err := strconv.ParseInt(raw, 10, 64); err == nil {
			return v
		}
	}
	return fallback
}

// SeedFromEnv returns pinned PRNG seed if EnvSeed is set, else fallback.
func SeedFromEnv(fallback uint32) uint32 {
	if raw := os.Getenv(EnvSeed); raw != "" {
		if v, err := strconv.ParseUint(raw, 10, 32); err == nil {
			return uint32(v)
		}
	}
	return fallback
}

// GeneratedGoSource returns the `pinned_gen.go` file scaffolded inside each unit package.
func GeneratedGoSource(pkgName string) string {
	return fmt.Sprintf(`// Code generated by request-anything. DO NOT EDIT.
package %s

import (
	"os"
	"strconv"
	"sync"
	"time"
)

var (
	pinMu       sync.Mutex
	pinState    uint32
	pinLastCase string
	pinStarted  bool
)

func pinnedNowMs() int64 {
	if raw := os.Getenv("REQUEST_ANYTHING_NOW_MS"); raw != "" {
		if v, err := strconv.ParseInt(raw, 10, 64); err == nil {
			return v
		}
	}
	return time.Now().UnixMilli()
}

func pinnedNowSecs() int64 {
	return pinnedNowMs() / 1000
}

func pinnedNextU32() uint32 {
	pinMu.Lock()
	defer pinMu.Unlock()
	c := os.Getenv("REQUEST_ANYTHING_CASE")
	if !pinStarted || (os.Getenv("REQUEST_ANYTHING_SEED") != "" && c != pinLastCase) {
		seed := uint32(time.Now().UnixNano())
		if raw := os.Getenv("REQUEST_ANYTHING_SEED"); raw != "" {
			if v, err := strconv.ParseUint(raw, 10, 32); err == nil {
				seed = uint32(v)
			}
		}
		pinState = seed
		pinLastCase = c
		pinStarted = true
	}
	pinState += 0x6D2B79F5
	t := (pinState ^ (pinState >> 15)) * (pinState | 1)
	t ^= t + ((t ^ (t >> 7)) * (t | 61))
	return t ^ (t >> 14)
}

func pinnedRandom() float64 {
	return float64(pinnedNextU32()) / 4294967296.0
}
`, pkgName)
}
