package shadow

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/TaTrap/request-anything/internal/models"
)

// Generate writes a drop-in shadow runner (`shadow_gen.go`) supporting REQUEST_ANYTHING_MODE=old|shadow|new.
func Generate(unitDir string, m models.UnitManifest) (string, error) {
	outPath := filepath.Join(unitDir, "shadow_gen.go")
	code := fmt.Sprintf(`// Code generated by request-anything. DO NOT EDIT.
package %s

import (
	"context"
	"fmt"
	"os"

	"github.com/TaTrap/request-anything/pkg/diff"
	"github.com/TaTrap/request-anything/pkg/models"
)

// ExecuteShadow runs Go port in shadow mode against a recorded/original baseline according to REQUEST_ANYTHING_MODE.
func ExecuteShadow(ctx context.Context, expected *models.WireRequest, actual *models.WireRequest, contract *models.ContractSpec) (*models.DiffResult, error) {
	mode := os.Getenv("REQUEST_ANYTHING_MODE")
	if mode == "" {
		mode = "shadow"
	}
	if mode == "old" {
		return &models.DiffResult{CaseID: %q, Passed: true, Summary: "mode=old (skipped Go port)"}, nil
	}
	res := diff.CompareRequests(ctx, %q, expected, actual, nil, nil, diff.Options{Contract: contract})
	if mode == "new" && !res.Passed {
		return res, fmt.Errorf("shadow mode=new parity failure: %%s", res.Summary)
	}
	return res, nil
}
`, m.PackageName, m.Unit, m.Unit)
	if err := os.WriteFile(outPath, []byte(code), 0o644); err != nil {
		return "", err
	}
	return outPath, nil
}
